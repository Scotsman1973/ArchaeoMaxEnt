import os.path

from qgis.PyQt.QtCore import QCoreApplication, QSettings, QTimer, QTranslator
from qgis.PyQt.QtGui import QIcon

try:  # Qt6 (QGIS 4) moved QAction to QtGui; Qt5 (QGIS 3) has it in QtWidgets.
    from qgis.PyQt.QtGui import QAction
except ImportError:
    from qgis.PyQt.QtWidgets import QAction

from .archaeoMaxEntDialog import ArchaeoMaxEntDialog

PLUGIN_NAME = "ArchaeoMaxEnt"
MENU_NAME = "&ArchaeoMaxEnt"
ICON_FILE = "icon.png"
TRANSLATION_FILE = "ArchaeoMaxEnt_{}.qm"


class ArchaeoMaxEntPlugin:
    """ArchaeoMaxEnt entry point for the QGIS plugin lifecycle."""

    def __init__(self, iface):
        """Store the QGIS interface and install a translation for the user's locale, if one exists.

        :param iface: The QgsInterface QGIS passes to plugins.
        """
        self.iface = iface
        self.pluginDir = os.path.dirname(__file__)
        self.dialog = None
        self.actions = []

        locale = (QSettings().value("locale/userLocale") or "")[0:2]
        localePath = os.path.join(self.pluginDir, "i18n", TRANSLATION_FILE.format(locale))
        if locale and os.path.exists(localePath):
            self.translator = QTranslator()
            self.translator.load(localePath)
            QCoreApplication.installTranslator(self.translator)

        self.menu = self.tr(MENU_NAME)

    def tr(self, message):
        """Translate message with the Qt translation API (this class is not a QObject)."""
        return QCoreApplication.translate(PLUGIN_NAME, message)

    def addAction(self, iconPath, text, callback, parent=None):
        """Create a menu entry and toolbar button that call callback, and return the action."""
        action = QAction(QIcon(iconPath), text, parent)
        action.triggered.connect(callback)
        self.iface.addToolBarIcon(action)
        self.iface.addPluginToMenu(self.menu, action)
        self.actions.append(action)
        return action

    def initGui(self):
        """Called by QGIS on load: add the plugin's menu entry and toolbar icon."""
        self.addAction(os.path.join(self.pluginDir, ICON_FILE), text=self.tr(PLUGIN_NAME), callback=self.run,
                       parent=self.iface.mainWindow())

    def unload(self):
        """Called by QGIS on unload: cancel any running task, remove the menu entry and toolbar icon."""
        if self.dialog is not None and self.dialog.activeTask is not None:
            self.dialog.activeTask.cancel()
        for action in self.actions:
            self.iface.removePluginMenu(self.menu, action)
            self.iface.removeToolBarIcon(action)
        self.actions = []
        self.dialog = None

    def run(self):
        """Open the modelling dialog, creating it on first use so it keeps its state between openings.

        The dialog is not modal, so the map and the task bar (with its Cancel
        button for long model runs) stay usable while it is open.
        """
        if self.dialog is None:
            self.dialog = ArchaeoMaxEntDialog(self.iface.mainWindow())
        self.dialog.show()
        self.dialog.raise_()
        self.dialog.activateWindow()
        # Once the window is on screen: offer to install the modelling tools if they are missing.
        dialog = self.dialog
        QTimer.singleShot(0, lambda: dialog.guard(dialog.offerRuntimeInstall))
